"""Reviewed upstream release manifest and Sigstore bundle store.

config/releases.json records, per app, the latest reviewed release tag, its
commit, one archive per supported platform (name/size/SHA-256 copied from the
release's SHA256SUMS.txt) and the read-only tool used for the smoke call, plus
the signers setup trusts. config/signatures.json holds, per archive, the
SHA-256 of the extracted CLI and the Sigstore bundle the daily workflow produced
by signing that CLI keyless with its own GitHub identity. Both are reviewed
source data regenerated by scripts/refresh_releases.py and
scripts/sign_releases.py; nothing at runtime fetches them from the network.
The retry policy those two scripts share for their network steps lives here.
"""
from __future__ import annotations
import http.client
from pathlib import Path
import re
import time
from typing import Callable, Sequence, TypeVar
import urllib.error
from .catalog import APP_IDS
from .common import ROOT, keys, load_json, require, sha, text

PLATFORMS = ('macos', 'linux-x86_64', 'windows-x64')
MAX_ASSET = 512 * 1024 * 1024
SIGSTORE_ISSUER = 'https://token.actions.githubusercontent.com'
RETRY_DELAYS = (15.0, 45.0)  # seconds slept before the second and the third attempt
T = TypeVar('T')

def asset_names(app: str, version: str, plat: str) -> list[str]:
    """Accepted archive names per platform; the first existing one is preferred."""
    if plat=='macos': return [f'{app}-cli-{version}-macos-universal.zip']
    if plat=='linux-x86_64': return [f'{app}-cli-{version}-linux-x86_64.tar.gz', f'{app}-{version}-linux-x86_64.tar.gz']
    return [f'{app}-cli-{version}-windows-x64.zip', f'{app}-{version}-windows-x64-portable.zip']

def load_releases(root: Path = ROOT) -> dict:
    data = keys(load_json(root/'config/releases.json'), {'schema_version','basis','reviewed','signers','apps'}, label='release manifest')
    require(type(data['schema_version']) is int and data['schema_version']==2, 'unsupported release manifest version')
    text(data['basis'], 'manifest basis', 1024)
    require(re.fullmatch(r'\d{4}-\d{2}-\d{2}', text(data['reviewed'], 'review date', 10)), 'review date must be YYYY-MM-DD')
    signers = keys(data['signers'], {'apple_team_id','sigstore_identity_regexp','sigstore_oidc_issuer'}, label='signers')
    require(re.fullmatch(r'[A-Z0-9]{10}', text(signers['apple_team_id'], 'Apple team id', 10)), 'Apple team id must be ten characters')
    re.compile(text(signers['sigstore_identity_regexp'], 'Sigstore identity', 512))
    require(signers['sigstore_oidc_issuer']==SIGSTORE_ISSUER, 'Sigstore issuer must be the GitHub Actions OIDC issuer')
    require(isinstance(data['apps'], dict) and set(data['apps'])==set(APP_IDS), 'release manifest must list exactly the thirteen apps')
    require(list(data['apps'])==sorted(data['apps']), 'release manifest apps must be sorted')
    for app, row in data['apps'].items():
        keys(row, {'tag','commit','version','smoke_tool','assets'}, label=f'release {app}')
        version = text(row['version'], 'version', 32)
        require(re.fullmatch(r'\d+\.\d+\.\d+', version), f'{app}: semantic version required')
        require(row['tag']=='v'+version, f'{app}: tag must be v<version>')
        require(isinstance(row['commit'], str) and re.fullmatch('[0-9a-f]{40}', row['commit']), f'{app}: tag commit must be a full lowercase SHA-1')
        require(re.fullmatch(r'[a-z][a-z0-9_]*', text(row['smoke_tool'], 'smoke tool', 128)), f'{app}: smoke tool must be a plain tool name')
        require(isinstance(row['assets'], dict) and set(row['assets'])==set(PLATFORMS), f'{app}: assets must cover exactly {", ".join(PLATFORMS)}')
        for plat, asset in row['assets'].items():
            keys(asset, {'name','sha256','bytes'}, label=f'{app} {plat} asset')
            require(asset['name'] in asset_names(app, version, plat), f'{app}: {plat} asset name is not a CLI archive for {version}')
            sha(asset['sha256'])
            require(type(asset['bytes']) is int and 0<asset['bytes']<=MAX_ASSET, f'{app}: asset size out of range')
    return data

def pinned_archives(releases: dict) -> dict[str, str]:
    """Archive name -> SHA-256 for every asset the manifest currently pins."""
    return {a['name']: a['sha256'] for row in releases['apps'].values() for a in row['assets'].values()}

def _store_shape(data: object, releases: dict) -> dict:
    """Structural, schema and signer-identity checks shared by the strict and the rotating loaders."""
    data = keys(data, {'schema_version','signed_by','bundles'}, label='signature store')
    require(type(data['schema_version']) is int and data['schema_version']==1, 'unsupported signature store version')
    require(data['signed_by']==releases['signers']['sigstore_identity_regexp'], 'signature store identity differs from the manifest signers')
    require(isinstance(data['bundles'], dict), 'signature store bundles must be an object')
    require(list(data['bundles'])==sorted(data['bundles']), 'signature store must be sorted')
    for name, entry in data['bundles'].items():
        text(name, 'archive name', 256)
        keys(entry, {'binary','binary_sha256','archive_sha256','bundle'}, label=f'signature {name}')
        text(entry['binary'], 'binary name', 64); sha(entry['binary_sha256']); sha(entry['archive_sha256'])
        require(isinstance(entry['bundle'], dict) and 'mediaType' in entry['bundle'] and 'verificationMaterial' in entry['bundle'],
                f'{name}: not a Sigstore bundle')
    return data

def validate_signature_store(data: object, releases: dict) -> dict:
    """Strict: every bundle must belong to an archive the manifest pins, with the pinned hash."""
    data = _store_shape(data, releases)
    known = pinned_archives(releases)
    require(set(data['bundles'])<=set(known), 'signature store names an archive the manifest does not pin')
    for name, entry in data['bundles'].items():
        require(entry['archive_sha256']==known[name], f'{name}: bundle was made for a different archive; re-sign')
    return data

def partition_signature_store(data: object, releases: dict) -> tuple[dict, dict]:
    """For rotation: the same shape and signer checks, then (still current, stale) by archive name and hash.

    Malformed entries and signer drift still raise; only entries the manifest no
    longer pins, or whose archive hash moved, are reported as stale.
    """
    data = _store_shape(data, releases)
    known = pinned_archives(releases)
    current = {n: e for n, e in data['bundles'].items() if n in known and e['archive_sha256']==known[n]}
    stale = {n: e for n, e in data['bundles'].items() if n not in current}
    return current, stale

def load_signatures(root: Path = ROOT, releases: dict | None = None) -> dict:
    return validate_signature_store(load_json(root/'config/signatures.json'), releases or load_releases(root))

def require_complete_bundles(signatures: dict, releases: dict) -> list[str]:
    """Strict release policy: every pinned archive on every platform has a current bundle."""
    missing = sorted(set(pinned_archives(releases)) - set(signatures.get('bundles', {})))
    require(not missing, 'archives without a Sigstore bundle: ' + ', '.join(missing))
    return sorted(signatures['bundles'])

def asset_url(app: str, row: dict, plat: str) -> str:
    return f"https://github.com/storytold/{app}/releases/download/{row['tag']}/{row['assets'][plat]['name']}"

def sums_url(app: str, row: dict) -> str:
    return f"https://github.com/storytold/{app}/releases/download/{row['tag']}/SHA256SUMS.txt"

def published_hash(sums: bytes, name: str) -> str:
    """The SHA-256 that upstream's SHA256SUMS.txt publishes for one asset name."""
    found = []
    for line in sums.decode('utf-8', 'replace').splitlines():
        parts = line.split()
        if len(parts)==2 and parts[1].lstrip('*')==name:
            found.append(parts[0].lower())
    require(len(found)==1, f'SHA256SUMS.txt must list {name} exactly once')
    return sha(found[0])

def transient(exc: BaseException) -> bool:
    """A network fault worth another attempt: a dropped or truncated connection, a 5xx or a 429.

    Any other HTTP error is a finding about the release (a 404 says the asset or
    SHA256SUMS.txt is not there), and a validation refusal (StorytoldError) is final.
    """
    if isinstance(exc, urllib.error.HTTPError):
        return exc.code == 429 or exc.code >= 500
    return isinstance(exc, (OSError, http.client.HTTPException))

def retrying(call: Callable[[], T], what: str, retry_if: Callable[[BaseException], bool], *,
             delays: Sequence[float] = RETRY_DELAYS, sleep: Callable[[float], None] = time.sleep,
             log: Callable[[str], None] = lambda s: None) -> T:
    """Return `call()`, repeating it after each delay while it raises what `retry_if` accepts; the last attempt's error propagates."""
    for delay in delays:
        try:
            return call()
        except Exception as exc:
            if not retry_if(exc):
                raise
            log(f'{what}: {exc}; retrying in {delay:g}s')
            sleep(delay)
    return call()
